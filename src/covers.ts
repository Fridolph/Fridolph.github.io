import type { Volume } from "./content";
import { drawCoverIcon } from "./icons";

export function makeCover(volume: Volume, index: number): HTMLCanvasElement {
  const canvas = document.createElement("canvas");
  canvas.width = 768;
  canvas.height = 1152;
  const context = canvas.getContext("2d")!;
  context.fillStyle = volume.color;
  context.fillRect(0, 0, canvas.width, canvas.height);
  context.fillStyle = "rgba(255,255,255,.035)";
  for (let stripe = 0; stripe < 768; stripe += 3) context.fillRect(stripe, 0, 1, 1152);
  context.fillStyle = "rgba(0,0,0,.045)";
  for (let stripe = 0; stripe < 1152; stripe += 4) context.fillRect(0, stripe, 768, 1);
  const spine = context.createLinearGradient(0, 0, 55, 0);
  spine.addColorStop(0, "rgba(0,0,0,.35)");
  spine.addColorStop(.55, "rgba(255,255,255,.1)");
  spine.addColorStop(1, "rgba(0,0,0,.03)");
  context.fillStyle = spine;
  context.fillRect(0, 0, 55, 1152);
  context.strokeStyle = volume.accent;
  context.fillStyle = volume.accent;
  context.lineWidth = 1;
  context.globalAlpha = .5;
  context.strokeRect(48, 40, 680, 1072);
  context.font = "17px monospace";
  context.fillText("FRIDOLPH / PERSONAL COLLECTION", 82, 100);
  context.fillText(String(index + 1).padStart(2, "0"), 650, 100);
  context.save();
  context.translate(400, 490);
  context.globalAlpha = .18;
  context.beginPath();
  context.arc(0, 0, 225, 0, Math.PI * 2);
  context.stroke();
  context.beginPath();
  context.arc(0, 0, 238, 0, Math.PI * 2);
  context.stroke();
  context.globalAlpha = .9;
  drawCoverIcon(context, volume.icon);
  context.restore();
  context.globalAlpha = .65;
  context.font = "16px monospace";
  context.textAlign = "center";
  context.fillText(`${String(volume.pages.length).padStart(2, "0")} PAGES / ${String(volume.pages.length / 2).padStart(2, "0")} CHAPTERS`, 400, 805);
  context.textAlign = "left";
  context.globalAlpha = 1;
  context.fillStyle = volume.accent;
  context.font = "76px Georgia, serif";
  context.fillText(volume.title, 80, 910);
  context.font = "22px 'Songti SC', 'Noto Serif CJK SC', serif";
  context.fillText(volume.subtitle, 84, 966);
  context.globalAlpha = .6;
  context.fillRect(84, 1030, 46, 2);
  context.font = "15px monospace";
  context.fillText(volume.category, 84, 1070);
  return canvas;
}
